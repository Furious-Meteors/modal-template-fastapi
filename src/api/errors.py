"""
src/api/errors.py
=================
One error shape for the whole API.

Every error response — auth, validation, domain, unmatched route, unexpected
failure — is the same flat JSON body:

    {"detail": "...", "session_id": "...", "error_code": "...", "errors": [...]}

`errors` is only present for request-validation failures and lists each
offending field.

Raise AppError from routes and dependencies. Plain HTTPException and
RequestValidationError are normalised by the handlers registered here.
"""
from __future__ import annotations

import logging
import uuid
from typing import Optional

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException

from src.api.models import ErrorDetail, FieldError
from src.core.domain.errors import DuplicateItemNameError

logger = logging.getLogger(__name__)

_STATUS_CODES = {
    400: "BAD_REQUEST",
    401: "UNAUTHORIZED",
    403: "FORBIDDEN",
    404: "NOT_FOUND",
    405: "METHOD_NOT_ALLOWED",
    409: "CONFLICT",
    422: "VALIDATION_ERROR",
    429: "TOO_MANY_REQUESTS",
}


class AppError(Exception):
    """An expected, client-visible error with a stable machine-readable code."""

    def __init__(
        self,
        status_code: int,
        error_code: str,
        message: str,
        headers: Optional[dict[str, str]] = None,
    ) -> None:
        super().__init__(message)
        self.status_code = status_code
        self.error_code = error_code
        self.message = message
        self.headers = headers


def get_session_id(request: Request) -> str:
    """
    The per-request ID generated by TelemetryMiddleware (request.state.session_id).
    Falls back to a fresh UUID if the middleware did not run, e.g. in a unit test
    that mounts a router on its own.
    """
    session_id = getattr(request.state, "session_id", None)
    if not session_id:
        session_id = str(uuid.uuid4())
        request.state.session_id = session_id
    return session_id


def _response(
    request: Request,
    status_code: int,
    error_code: str,
    message: str,
    *,
    errors: Optional[list[FieldError]] = None,
    headers: Optional[dict[str, str]] = None,
) -> JSONResponse:
    body = ErrorDetail(
        detail=message,
        session_id=get_session_id(request),
        error_code=error_code,
        errors=errors,
    )
    return JSONResponse(
        status_code=status_code,
        content=body.model_dump(exclude_none=True),
        headers=headers,
    )


async def _app_error_handler(request: Request, exc: AppError) -> JSONResponse:
    return _response(request, exc.status_code, exc.error_code, exc.message, headers=exc.headers)


async def _http_exception_handler(request: Request, exc: StarletteHTTPException) -> JSONResponse:
    return _response(
        request,
        exc.status_code,
        _STATUS_CODES.get(exc.status_code, "HTTP_ERROR"),
        str(exc.detail),
        headers=getattr(exc, "headers", None),
    )


async def _validation_error_handler(request: Request, exc: RequestValidationError) -> JSONResponse:
    errors = [
        FieldError(
            field=".".join(str(part) for part in err.get("loc", ())),
            message=str(err.get("msg", "")),
            type=str(err.get("type", "")),
        )
        for err in exc.errors()
    ]
    return _response(
        request,
        422,
        "VALIDATION_ERROR",
        "Request validation failed",
        errors=errors,
    )


async def _duplicate_item_name_handler(
    request: Request, exc: DuplicateItemNameError
) -> JSONResponse:
    return _response(request, 409, "ITEM_NAME_EXISTS", str(exc))


async def _unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    # Runs in ServerErrorMiddleware, outside TelemetryMiddleware, so the
    # x-session-id header has to be set here. The exception is still re-raised
    # afterwards by Starlette so servers and test clients see it.
    logger.exception("Unhandled exception on %s %s", request.method, request.url.path)
    session_id = get_session_id(request)
    return _response(
        request,
        500,
        "INTERNAL_ERROR",
        "Internal server error",
        headers={"x-session-id": session_id},
    )


def register_exception_handlers(app: FastAPI) -> None:
    app.add_exception_handler(AppError, _app_error_handler)
    app.add_exception_handler(StarletteHTTPException, _http_exception_handler)
    app.add_exception_handler(RequestValidationError, _validation_error_handler)
    app.add_exception_handler(DuplicateItemNameError, _duplicate_item_name_handler)
    app.add_exception_handler(Exception, _unhandled_exception_handler)
